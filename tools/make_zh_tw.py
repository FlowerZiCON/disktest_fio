def convert(text):
    # 先按词表换大陆用语，再做简→繁逐字符转换。
    # 顺序很重要：「磁盘」先变成「磁碟」，后面的「…的盘」「盘上」才不会再
    # 命中「磁盘上」里面的那个「盘」（否则会出现"磁磁碟"）。
    for source, target in TERMS:
        text = text.replace(source, target)
    for source, target in PHRASES:
        text = text.replace(source, target)
    text = zhconv.convert(text, "zh-tw")
    return text


def main():
    def_text = io.open(os.path.join(ROOT, "src", "uitext.def"), encoding="utf-8").read()
    text = "\n".join("" if line.lstrip().startswith("//") else line
                     for line in def_text.splitlines())

    rows = []
    pos = 0
    while True:
        match = ENTRY.search(text, pos)
        if not match:
            break
        body, end = read_literal_block(text, match.end())
        rows.append((match.group(1), literals_of(body)))
        pos = end

    out = ["# disktest 的繁體中文介面文字（由 tools/make_zh_tw.py 從 src/uitext.def 生成）\n",
           "#\n",
           "# 一行一條：`鍵<TAB>譯文`。改成手工維護也可以，只是下次跑生成腳本會被覆蓋。\n",
           "# 譯文裡的 `\\n` 是換行；%1 %2 這些佔位符一個都不能少。\n",
           "# 改完跑一次 `disktest.exe --i18n-check`。\n",
           "#\n"]
    for key, source in rows:
        out.append("%s\t%s\n" % (key, convert(source)))

    body = "".join(out)
    if "--stdout" in sys.argv:
        sys.stdout.buffer.write(body.encode("utf-8"))
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(body)
    print("wrote %s (%d entries)" % (OUT, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
